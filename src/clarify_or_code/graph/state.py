"""LangGraph state definition for Clarify-or-Code.

Purpose: Defines real typed shared graph state used across all specialist agents.
Phase: Phase 0 (Foundation).
Serves: Supervisor, Issue Analyst, Code Locator, Clarifier, Fixer, Test Runner, Reviewer, PR Writer.
"""

from typing import Literal

from pydantic import BaseModel, Field

from clarify_or_code.agents.schemas import (
    ClarificationResult,
    IssueAnalysis,
    PatchPlan,
    ReviewResult,
    TestExecutionResult,
)


class AgentState(BaseModel):
    """Shared state dictionary passed across LangGraph nodes."""

    # Input & Ingestion
    issue_url: str = Field(default="", description="Target GitHub issue URL")
    issue_text: str = Field(default="", description="Sanitized text of issue title, body, and comments")
    repo_url: str = Field(default="", description="Target repository URL")
    workspace_path: str = Field(default="", description="Local isolated git worktree directory path")

    # Ingestion & Localization outputs
    analysis: IssueAnalysis | None = Field(default=None, description="Output from Issue Analyst")
    relevant_files: list[str] = Field(default_factory=list, description="Candidate files located by Code Locator")

    # Clarification
    clarification: ClarificationResult | None = Field(default=None, description="Output from Clarifier agent")

    # Fix & Patch
    plan: PatchPlan | None = Field(default=None, description="Fixer agent plan")
    patch: str = Field(default="", description="Unified git diff patch generated by Fixer")

    # Testing & Verification
    test_results: TestExecutionResult | None = Field(default=None, description="Output from deterministic Test Runner")
    retry_count: int = Field(default=0, description="Current repair retry iteration count (max 3)")

    # Review & PR
    review_result: ReviewResult | None = Field(default=None, description="Output from Reviewer agent")
    pr_url: str | None = Field(default=None, description="Draft PR URL opened by PR Writer")

    # Lifecycle & Observability
    total_cost_usd: float = Field(default=0.0, description="Accumulated LLM cost in USD across all agent calls")
    status: Literal["pending", "analyzing", "locating", "clarifying", "fixing", "testing", "reviewing", "opening_pr", "resolved", "failed"] = Field(
        default="pending", description="Overall execution status"
    )
